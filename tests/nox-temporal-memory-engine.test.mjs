import assert from "node:assert/strict";
import { NOXTemporalMemoryEngine } from "../core/nox-temporal-memory-engine.js";

const engine = new NOXTemporalMemoryEngine();
const lite = engine.configure(640, 480, { lowPower: true });
assert.deepEqual([lite.sampleWidth, lite.sampleHeight, lite.bufferCount, lite.intervalMs], [160, 120, 3, 180]);
assert.equal(engine.getCaptureDecision(1000).capture, true);
engine.commitCapture(1000);
assert.equal(engine.getCaptureDecision(1179).capture, false);
assert.equal(engine.getCaptureDecision(1180).capture, true);
engine.commitCapture(1180);
const trace = engine.getCompositePlan("motion-trace", 640, false);
assert.equal(trace.length, 2);
assert.ok(trace.every(layer => layer.alpha > 0 && layer.alpha < 1 && layer.offset === 0));
const echo = engine.getCompositePlan("time-echo", 640, false);
assert.equal(echo.length, 2);
assert.ok(echo.every(layer => layer.offset > 0));
assert.deepEqual(engine.getCompositePlan("off", 640), []);
engine.commitCapture(1360);
assert.equal(engine.getStatus().frameCount, 3);
engine.commitCapture(1540);
assert.equal(engine.getStatus().frameCount, 3);
assert.equal(engine.getStatus().writeIndex, 1);
const standard = engine.configure(640, 480, { lowPower: false });
assert.deepEqual([standard.sampleWidth, standard.sampleHeight, standard.bufferCount, standard.intervalMs], [224, 168, 4, 120]);
assert.equal(engine.getStatus().frameCount, 0);
assert.throws(() => engine.configure(0, 480), /invalid-temporal-frame-size/);
assert.throws(() => engine.getCaptureDecision(NaN), /invalid-temporal-timestamp/);
engine.reset();
assert.equal(engine.getStatus().configured, false);
assert.equal(engine.getStatus().frameCount, 0);
console.log("NOX temporal memory engine tests passed");
